// Canonical translations live in the standalone JSON; LuCI's PO is generated.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { argv } from 'node:process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const messages = JSON.parse(readFileSync(resolve(root, 'luci-app-familycontrol/root/www/family/messages.zh-CN.json'), 'utf8'));
let content = '# Generated by scripts/generate-translations.mjs; edit messages.zh-CN.json.\n';
content += 'msgid ""\nmsgstr ""\n"Content-Type: text/plain; charset=UTF-8\\n"\n"Language: zh_Hans\\n"\n';
for (const key of Object.keys(messages).sort()) {
	assert(key && typeof messages[key] === 'string' && messages[key]);
	assert.deepEqual(messages[key].match(/%[sd]/g) || [], key.match(/%[sd]/g) || [],
		`Translation placeholders differ: ${key}`);
	content += `\nmsgid ${JSON.stringify(key)}\nmsgstr ${JSON.stringify(messages[key])}\n`;
}
const target = resolve(root, 'luci-app-familycontrol/po/zh_Hans/familycontrol.po');
if (argv.includes('--check'))
	assert.equal(readFileSync(target, 'utf8'), content, 'Regenerate the LuCI translation catalog');
else {
	mkdirSync(dirname(target), {recursive: true});
	writeFileSync(target, content, 'utf8');
}
